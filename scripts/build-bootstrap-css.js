const fs = require("node:fs");
const path = require("node:path");
const { createRequire } = require("node:module");
const postcss = createRequire(require.resolve("next/package.json"))("postcss");

const root = path.resolve(__dirname, "..");
const source = path.join(root, "src/assets/css/bootstrap.min.css");
const output = path.join(root, "src/assets/css/bootstrap.generated.css");
const used = new Set();
// React Bootstrap also composes these utility names from numeric props.
const dynamicPrefixes = new Set(["gap-", "order-"]);
const extensions = new Set([".js", ".jsx", ".ts", ".tsx", ".json", ".html", ".css"]);

function scan(directory) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      scan(file);
    } else if (extensions.has(path.extname(file)) && file !== source && file !== output) {
      const text = fs.readFileSync(file, "utf8");
      for (const token of text.match(/[A-Za-z0-9_-]+/g) || []) used.add(token);
      for (const match of text.matchAll(/([A-Za-z0-9_-]+-)\$\{|["'`]([A-Za-z0-9_-]+-)["'`]\s*\+/g)) {
        dynamicPrefixes.add(match[1] || match[2]);
      }
    }
  }
}

scan(path.join(root, "src"));
scan(path.join(root, "public"));
scan(path.dirname(require.resolve("react-bootstrap/package.json")));

// Limit pruning to standalone layout utilities. Keep Bootstrap's grid,
// components, typography, colors, transitions, keyframes and font rules.
const utility = /^(?:(?:m|p)[trblxyse]?|d|gap|order|flex|justify-content|align-items|align-content|align-self|w|h|mw|mh|position|top|bottom|start|end|translate-middle|float|overflow|visible|invisible)(?:-|$)/;
const css = postcss.parse(fs.readFileSync(source, "utf8"));
let removed = 0;

css.walkRules((rule) => {
  const selectors = rule.selector.split(",").map((selector) => selector.trim());
  if (selectors.every((selector) => {
    if (!/^\.[A-Za-z0-9_-]+$/.test(selector)) return false;
    const name = selector.slice(1);
    return utility.test(name) && !used.has(name) &&
      ![...dynamicPrefixes].some((prefix) => name.startsWith(prefix));
  })) {
    removed++;
    rule.remove();
  }
});

fs.writeFileSync(output, `/* Generated by scripts/build-bootstrap-css.js; edit bootstrap.min.css instead. */\n${css}`);
console.log(`Bootstrap CSS: removed ${removed} unused layout utility rules.`);
