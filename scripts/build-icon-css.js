const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const source = path.join(root, "src/assets/css/all.min.css");
const output = path.join(root, "src/assets/css/icons.generated.css");
const extensions = new Set([".js", ".jsx", ".ts", ".tsx", ".json", ".css", ".html"]);
const used = new Set();

function scan(directory) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      scan(file);
    } else if (extensions.has(path.extname(file)) && file !== source && file !== output) {
      const text = fs.readFileSync(file, "utf8");
      // Fail rather than omit icons if future code constructs names at runtime.
      if (/fa-\$\{|["'`]fa-["'`]\s*\+/.test(text)) {
        throw new Error(`Dynamic icon names need explicit full names in ${file}`);
      }
      for (const match of text.matchAll(/\bfa-[a-z0-9-]+\b/g)) used.add(match[0]);
    }
  }
}

scan(path.join(root, "src"));
scan(path.join(root, "public"));

const original = fs.readFileSync(source, "utf8");
let removed = 0;
// Remove only standalone glyph mappings. Keep all font faces, utilities,
// animations, media queries, and every alias of a referenced icon unchanged.
const css = original.replace(
  /^(?:\.fa-[a-z0-9-]+::?before\s*,?\s*)+\{\s*content:\s*"\\[0-9a-fA-F]+";\s*\}/gm,
  (rule) => {
    const names = [...rule.matchAll(/\.([a-z0-9-]+):/g)].map((match) => match[1]);
    if (names.some((name) => used.has(name))) return rule;
    removed++;
    return "";
  },
);

fs.writeFileSync(output, `/* Generated by scripts/build-icon-css.js; edit all.min.css instead. */\n${css}`);
console.log(`Icon CSS: removed ${removed} unused glyph rules; ${Buffer.byteLength(original)} -> ${Buffer.byteLength(css)} bytes.`);
